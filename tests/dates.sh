#!/bin/sh
# tests/dates.sh — **日期运算**：给明确日期就算，没有时钟就如实说（§6.804）
#
# 判据：
#   ① 加减天数（含闰年 2024-02-28 + 1 = 2024-02-29、跨年）；
#   ② 两个日期差几天（两个方向都对）；
#   ③ 星期几（和系统 date 对过：2026-03-01 = 周日、2024-02-29 = 周四）；
#   ④ 月和年的加减**明确拒绝**（月末约定各家不同，不猜）；
#   ⑤ 不给日期时说"没有时钟"（不是编一个日期）；
#   ⑥ 连续折扣（§6.804 同批）：先打八折再打九折 = 72%。
set -u
ROOT=$(cd "$(dirname "$0")/.." && pwd)
MODEL=${1:-$ROOT/model.bin}
cd "$ROOT"
[ -x ./build_aip ] || sh "$ROOT/tests/prebuilt.sh" aip "$ROOT/main.c" -std=c11 -O2 -Wall -Wextra
[ -x ./build_aip ] || { echo "FAIL: 编不出 build_aip"; exit 1; }
W="$ROOT/_t/dates"; rm -rf "$W"; mkdir -p "$W"
cp "$MODEL" "$W/m.bin"
pass=0; fail=0
ok()  { printf '  [OK]   %-34s %s\n' "$1" "$2"; pass=$((pass + 1)); }
bad() { printf '  [FAIL] %-34s\n         证据: %s\n' "$1" "${2:-}"; fail=$((fail + 1)); }
ans() { printf '%b\n::quit\n' "$1" | ./build_aip --model "$W/m.bin" 2>&1 | grep -a 'AI > ' | head -1 | sed 's/.*AI > //'; }
chk() { r=$(ans "$1"); printf '%s' "$r" | grep -qF -- "$2" && ok "$3" "$r" || bad "$3" "$r"; }

chk '2026-03-01 之后 30 天 是 几号' '2026-03-31' '加天数（跨月）'
chk '2026-03-01 之前 10 天'        '2026-02-19' '减天数（跨月）'
chk '2024-02-28 之后 1 天'         '2024-02-29' '闰年 2 月'
chk '2024-02-29 之后 1 天'         '2024-03-01' '闰年第二天'
chk '2026-03-01 之前 400 天'       '2025-01-25' '减天数（跨年）'
chk '2026-03-01 和 2026-03-15 差 几 天' '14 天' '两个日期差'
chk '2026-03-15 和 2026-03-01 差 几 天' '14 天' '差（反方向也是 14）'
chk '2026-03-01 是 星期 几'        '周日'       '星期几（和 date 对过）'
chk '2024-02-29 是 星期 几'        '周四'       '闰日星期几'

echo "== 明确拒绝 / 如实说 =="
r=$(ans '2026-01-31 之后 1 个月')
printf '%s' "$r" | grep -q '不猜' && ok "月加减拒绝（月末约定）" "$r" || bad "月加减没拒绝" "$r"
r=$(ans '现在几点')
printf '%s' "$r" | grep -qE '没有 时 钟|没 有 时 钟|不 知道' && ok "没给日期时如实说" "$r" || bad "没给日期却答了" "$r"

echo "== 连续折扣（§6.804） =="
r=$(ans '先打八折 再打九折')
printf '%s' "$r" | grep -q '72%' && ok "八折再九折 = 72%" "$r" || bad "连续折扣不对" "$r"
r=$(ans '100 元 先打八折 再打九折')
printf '%s' "$r" | grep -q '= 72' && ok "100 元连续折 = 72 元" "$r" || bad "连续折扣价格不对" "$r"

printf '\n日期/连续折扣：%d 过 / %d 红\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
